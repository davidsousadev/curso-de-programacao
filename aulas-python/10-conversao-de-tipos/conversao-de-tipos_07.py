# 10 - 06 - Exemplos de conversões

PI = "3.14159"
print(type(PI), PI)
ponto_flutuante=float(PI)
print(type(ponto_flutuante), ponto_flutuante)
inteiro=int(ponto_flutuante)
print(type(inteiro), inteiro)
booleano=bool(inteiro)
print(type(booleano), booleano)
string=str(booleano)
print(type(string), string)
lista=list(string)
print(type(lista), lista)